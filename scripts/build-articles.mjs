#!/usr/bin/env node
/**
 * Renders the Substack feed into education.html as plain HTML.
 *
 * Articles used to be fetched in the browser through api.rss2json.com, which now
 * sits behind a bot challenge — that is what left the page stuck on
 * "Loading articles...". Crawlers also skip content that arrives via JavaScript,
 * so the cards are baked into the page instead.
 *
 * A daily launchd job on the maintainer's Mac runs this and pushes any change,
 * which redeploys the site (Substack 403s GitHub Actions runners). Run
 * `npm run articles` locally to pull a post in sooner.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = join(ROOT, 'education.html');
const FEED = 'https://graysmithproperties.substack.com/feed';
const MAX_ARTICLES = 12;

const START = '<!-- ARTICLES:START — generated by scripts/build-articles.mjs, do not edit by hand -->';
const END = '<!-- ARTICLES:END -->';

const THUMBS = ['t1', 't2', 't3', 't4'];
const STAGGER = ['', 'stagger-1', 'stagger-2', 'stagger-3'];

/** Topic pills have no equivalent in the Substack feed, so derive them from the text. */
const TOPIC_RULES = [
  ['buying', /\bbuy(ing|er|ers)?\b|\brent(ing)?\b|first home|move[- ]in/i],
  ['selling', /\bsell(ing|er|ers)?\b|\blist(ing|ed)?\b|top dollar|showing/i],
  ['wealth', /wealth|equity|net worth|cheat code|build(ing)? .*(wealth|value)/i],
  ['market', /market|price(s|d)?|rate(s)?|dallas|inventory|softened/i],
  ['equity', /equity|appraisal|apprecia|home value|refinanc/i],
  ['investing', /invest(ing|or|ors|ment)?|rental|flip|house hack|cash flow|cap rate/i],
];

function textOf(xml, tag) {
  const m = xml.match(new RegExp(`<${tag}>(?:<!\\[CDATA\\[)?([\\s\\S]*?)(?:\\]\\]>)?</${tag}>`));
  return m ? m[1].trim() : '';
}

function stripHtml(s) {
  return s.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
}

/** Decode the entity subset Substack actually emits, then re-escape for our markup. */
function decodeEntities(s) {
  return s
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&');
}

function escapeHtml(s) {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function clean(s) {
  return escapeHtml(decodeEntities(stripHtml(s)));
}

function topicsFor(item) {
  const haystack = `${item.title} ${item.excerpt}`;
  const hits = TOPIC_RULES.filter(([, re]) => re.test(haystack)).map(([t]) => t);
  return hits.join(' ');
}

function formatDate(pubDate) {
  const d = new Date(pubDate);
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString('en-US', {
    month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC',
  });
}

/**
 * Cover image for a post. Posts without one get the publication's own image as
 * their enclosure, which would put the same logo on every card, so skip that.
 * Substack's CDN resizes on request; 800px wide covers the card at 2x.
 */
function coverFor(raw, channelImage) {
  const m = raw.match(/<enclosure[^>]*\burl="([^"]+)"[^>]*\btype="image\//);
  if (!m) return '';
  const url = decodeEntities(m[1]);
  if (url === channelImage) return '';
  const sized = url.includes(',w_') ? url : url.replace(/(\/image\/fetch\/[^/,]+),/, '$1,w_800,c_limit,');
  return escapeHtml(sized);
}

function parseFeed(xml) {
  const channelImage = decodeEntities(textOf(textOf(xml, 'image'), 'url'));
  const items = xml.match(/<item>[\s\S]*?<\/item>/g) || [];
  return items.slice(0, MAX_ARTICLES).map((raw) => {
    const description = textOf(raw, 'description');
    let excerpt = clean(description);
    if (excerpt.length > 160) excerpt = `${excerpt.slice(0, 160).trimEnd()}...`;
    return {
      title: clean(textOf(raw, 'title')),
      link: textOf(raw, 'link'),
      date: formatDate(textOf(raw, 'pubDate')),
      excerpt,
      image: coverFor(raw, channelImage),
    };
  });
}

function renderCard(item, i) {
  const topics = topicsFor(item);
  return `      <a href="${item.link}" target="_blank" rel="noopener" class="article-card fade-up ${STAGGER[i % STAGGER.length]}"${topics ? ` data-topics="${topics}"` : ''}>
        <div class="article-thumb ${THUMBS[i % THUMBS.length]}">
          <svg width="60" height="60" viewBox="0 0 60 60" fill="none">
            <path d="M15 20h30M15 30h30M15 40h20" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" opacity="0.2"/>
          </svg>
${item.image ? `          <img src="${item.image}" alt="" loading="lazy" decoding="async">\n` : ''}        </div>
        <div class="article-content">
${item.date ? `          <div class="article-topic">${item.date}</div>\n` : ''}          <h3 class="article-title">${item.title}</h3>
          <p class="article-excerpt">${item.excerpt}</p>
          <span class="article-read">
            Read on Substack
            <svg width="14" height="14" viewBox="0 0 16 16" fill="none"><path d="M3 8h10M9 4l4 4-4 4" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/></svg>
          </span>
        </div>
      </a>`;
}

async function main() {
  const res = await fetch(FEED, { headers: { 'User-Agent': 'graysmithproperties-build/1.0' } });
  if (!res.ok) throw new Error(`Feed request failed: ${res.status} ${res.statusText}`);

  const articles = parseFeed(await res.text());
  if (articles.length === 0) throw new Error('Feed returned no items — refusing to blank the page.');

  const page = await readFile(PAGE, 'utf8');
  const from = page.indexOf(START);
  const to = page.indexOf(END);
  if (from === -1 || to === -1) throw new Error(`Markers not found in ${PAGE}`);

  const block = `${START}\n${articles.map(renderCard).join('\n')}\n      ${END}`;
  await writeFile(PAGE, page.slice(0, from) + block + page.slice(to + END.length));

  console.log(`Wrote ${articles.length} articles into education.html`);
  console.log(`  newest: ${decodeEntities(articles[0].title)}`);
}

main().catch((err) => {
  console.error(`build-articles failed: ${err.message}`);
  process.exitCode = 1;
});
